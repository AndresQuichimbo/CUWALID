def _load_raster_or_netcdf_array(fname, field=None, flatten=True):
	"""Load a raster or NetCDF file as a numpy array.

	NetCDF inputs are handled through xarray and raster inputs through
	`read_raster`. If a NetCDF file has a time dimension, the first time slice
	is used by default.
	"""
	if fname is None:
		raise ValueError("fname must not be None")

	fname_lower = fname.lower()
	if fname_lower.endswith((".nc", ".nc4", ".cdf")):
		ds = xr.open_dataset(fname)
		try:
			if field is not None and field in ds.variables:
				data = ds[field]
			elif field is not None:
				# Fall back to the first data variable when the requested field is absent.
				data_var_names = list(ds.data_vars)
				if not data_var_names:
					raise KeyError("NetCDF file does not contain data variables")
				data = ds[data_var_names[0]]
			else:
				data_var_names = list(ds.data_vars)
				if not data_var_names:
					raise KeyError("NetCDF file does not contain data variables")
				data = ds[data_var_names[0]]

			if "time" in data.dims:
				data = data.isel(time=0)

			array = np.asarray(data.values)
		finally:
			ds.close()
	else:
		array = read_raster(fname, flatten=False)

	if flatten:
		return np.asarray(array).reshape(-1)
	return np.asarray(array)

def get_flow_path(fname_surface, fname_outlet, fname_out=None,
						fname_flowDir=None, fname_mask=None,
						accum=True, flowdir_format='DRYP'):
	"""Function to create flow path map if the location of the input points
	is provided. This function requires a flow direction map
	but if not provided the flow direction will be created. The function also
	creates a flow accumulation along the path, which is equivalent to the path
	length map.

	Parameters:
	-----------
	fname_surface: str
		file name of the elevation raster map
	fname_outlet : str
		file name of the outflow raster map
	fname_flowdir : str
		(optional) filename of the flow direction raster map
	fname_out : str
		(optional) filename of the output raster file
	fname_mask : str
		(optional) filename of the mask raster file
	accum : bool
		(optional) value that specify if the flow accumulation map is created
	flowdir_format: str
		(optional) value that specify the flow direction format (D8, LDD, GRASS, AGNPS, landlab, DRYP)


	Returns:
	--------
	file
		csv file containing a list areas and node index
		asc flow accumalation map as raster file

		
	Examples:
	---------

	>>> from cuwalid.dryp.components.DRYP_watershed import get_watershed_map
	>>> fname_surface = "surface.asc"
	>>> fname_flowdir = "flowdir.asc"
	>>> fname_outlet = "point.csv"

	>>> get_flow_path(fname_surface, fname_outlet, fname_flowdir)

	"""

	# read datasets: surface, flow direction, and list of points
	surface = read_raster(fname_surface)
	
	# read flow direction
	flowDir = None
	if fname_flowDir is not None:
		if flowdir_format != "DRYP":
			flowDir = open_raster(fname_flowDir)[0]
			flowDir = transform_flowdirection_d8_to_landlab_array(
				flowDir, format_data=flowdir_format)
			flowDir = np.flip(flowDir, 0).flatten()
		else:
			flowDir = read_raster(fname_flowDir)
	
	## get raster shape and cellsize
	domain = rasterio.open(fname_surface)
	#grid_shape = (domain.height, domain.width)
	grid_size = (domain.height*domain.width)
	#grid_size = int(domain.nrows*domain.ncols)
	area_cell = np.power(domain.transform[0], 2)

	# read mask
	mask = None
	if fname_mask is not None:
		mask = read_raster(fname_mask)

	# create a raster grid environment, landlab grid
	grid = create_grid_from_extent(
	#grid = create_landlab_grid(
		domain.width,
		domain.height,
		domain.bounds[0],
		domain.bounds[1],
		domain.transform[0], # cell size
		mask)
	
	ro = runoff_routing(grid,
		 	grid_size,
			surface, 
			flowDir,
			np.zeros_like(surface),
			np.zeros_like(surface),
			np.zeros_like(surface),
			np.zeros_like(surface),
			)

	# get basin outlets
	# Output variables and location
	idnodes = get_index_from_coord_file(grid, fname_outlet)[0]

	# create a raster dataset
	unit_area = np.zeros_like(surface)
	
	# create a new raster with the lozation to track
	unit_area[idnodes] = 1.0

	# run runoff component to generate the flow path,
	# the flow path is generated by routing the unit area
	# from the outlet to the catchemnt outlet
	ro.run_runoff_one_step(
						unit_area,# unit area
						np.zeros_like(surface),#AOF
						np.zeros_like(surface),#AOF_threshold,
						np.zeros_like(surface), #conductivity,
						np.ones_like(surface),
						np.zeros_like(surface),# no rivers
						np.full(grid_size, area_cell),
						np.zeros_like(surface),
						np.ones_like(surface)*1e5,
						None)

	# The flow path obtained from the previous step is then used to calculate
	# the flow accumulation map along the flow path
	if accum is True:
		# run runoff component
		ro.run_runoff_one_step(
						ro.discharge,# unit area
						np.zeros_like(surface),#AOF
						np.zeros_like(surface),#AOF_threshold,
						np.zeros_like(surface), #conductivity,
						np.ones_like(surface),
						np.zeros_like(surface),# no rivers
						np.full(grid_size, area_cell),
						np.zeros_like(surface),
						np.ones_like(surface)*1e5,
						None)
	# save files
	if fname_out is None:
		fname_out = fname_surface.split('.')[0]

	# Save contributing area as raster file
	save_map_to_rastergrid(grid, ro.discharge,
			fname_out + '_flowpath.asc')

def get_flow_accumulation(fname_surface, fname_flow_unit_rate=None, fname_out=None,
						fname_flowDir=None, fname_mask=None, field=None, flowdir_format='DRYP',
						dtype='float32', Volume=False):
	"""This function calculates the flow accumulation map.
	It requires a flow direction map and an the flow unit rate map.
	If the flow unit rate map is not provided, the function will
	create a flow unit rate map.

	This function store all files in the same directory of the
	output files if post processing directory is not provided.
	
	Parameters
	----------
	fname_surface: str
		file name of the elevation raster map
	fname_flow_unit_rate : str
		file name of the flow unit rate raster map, or netcdf file containing the flow unit rate variable (field)
	fname_flowDir : str
		(optional) filename of the flow direction raster map
	fname_mask : str
		(optional) filename of the mask raster file
	fname_out : str
		(optional) filename of the output raster file
	field: str
		(optional) field name of the flow unit rate in case the flow unit rate file is a netcdf file
	flowdir_format: str
		(optional) value that specify the flow direction format (D8, LDD, GRASS, AGNPS, landlab, DRYP)
	dtype: data type of the output raster file (default: np.float32)
	Volume: bool
		(optional) if True, the flow accumulation map will be calculated in terms of volume

	Returns
	-------
	file
		asc flow accumalation map as raster file

		
	Examples
	--------

	>>> from cuwalid.dryp.components.DRYP_watershed import get_flow_accumulation
	>>> fname_surface = "surface.asc"
	>>> fname_flow_unit_rate = "flow_unit_rate.asc"
	>>> fname_flowdir = "flowdir.asc"

	>>> get_flow_accumulation(fname_surface, fname_flow_unit_rate, fname_flowdir)
	"""

	# read datasets: surface, flow direction, and list of points
	surface = read_raster(fname_surface)
	
	# read flow direction
	flowDir = None
	if fname_flowDir is not None:
		if flowdir_format != "DRYP":
			flowDir = open_raster(fname_flowDir)[0]
			flowDir = transform_flowdirection_d8_to_landlab_array(
				flowDir, format_data=flowdir_format)
			flowDir = np.flip(flowDir, 0).flatten()
		else:
			flowDir = read_raster(fname_flowDir)
	
	## get raster shape and cellsize
	domain = rasterio.open(fname_surface)
	#grid_shape = (domain.height, domain.width)
	grid_size = (domain.height*domain.width)
	#grid_size = int(domain.nrows*domain.ncols)
	if Volume is True:
		area_cell = np.power(domain.transform[0], 2)
	else:
		area_cell = 1.0

	# read mask
	mask = None
	if fname_mask is not None:
		mask = read_raster(fname_mask)

	# create a raster grid environment, landlab grid
	grid = create_grid_from_extent(
	#grid = create_landlab_grid(
		domain.width,
		domain.height,
		domain.bounds[0],
		domain.bounds[1],
		domain.transform[0], # cell size
		mask)
	
	ro = runoff_routing(grid,
		 	grid_size,
			surface, 
			flowDir,
			np.zeros_like(surface),
			np.zeros_like(surface),
			np.zeros_like(surface),
			np.zeros_like(surface),
			)

	# read flow unit rate
	if fname_flow_unit_rate is not None:
		try:
			flow_unit_rate = _load_raster_or_netcdf_array(fname_flow_unit_rate, field=field, flatten=True)
		except Exception as exc:
			print(f'Flow unit rate file not found or unreadable ({fname_flow_unit_rate}). unit values used instead')
			print(exc)
			flow_unit_rate = np.ones_like(surface)
	else:
		print('Flow unit rate file not found. unit values used instead')
		flow_unit_rate = np.ones_like(surface)

	# runoff component to generate the flow accumulation map
	ro.run_runoff_one_step(
						flow_unit_rate,# unit area
						np.zeros_like(surface),#AOF
						np.zeros_like(surface),#AOF_threshold,
						np.zeros_like(surface), #conductivity,
						np.ones_like(surface),
						np.zeros_like(surface),# no rivers
						np.full(grid_size, area_cell),
						np.zeros_like(surface),
						np.ones_like(surface)*1e5,
						None)
	
	# get raster file properties
	_, profile, transform = open_raster(fname_surface)

	# update profile for output raster
	profile = profile.copy()
	if dtype is not None:
		profile['dtype'] = dtype
	
	# save files
	if fname_out is None:
		fname_out = fname_surface.split('.')[0]
		fname_out = fname_out + '_var_flowaccum.asc'

	# Save contributing area as raster file
	save_raster(fname_out, np.flip(ro.discharge.reshape((domain.height,domain.width)), 0),
			 profile, transform)
	
	print(f"Flow accumulation map saved:\n{fname_out}")

